db.groups = groups;
db.tests = [];
db.questions = [];

for (let i = 0; i < tests.length; i++) {
  const test = tests[i];
  test.groupIds = [groups[i].id];
  db.tests.push(test);
  const source = tests[i];
  const questionData = source.questions;
  if (!questionData) continue;
  questionData.forEach((item, questionIndex) => {
    const [text, ...rest] = item;
    const correctIndex = rest.pop();
    db.questions.push({
      id: crypto.randomUUID(),
      testId: test.id,
      text,
      position: questionIndex,
      options: rest.map((optionText, optionIndex) => ({
        id: crypto.randomUUID(),
        text: optionText,
        isCorrect: optionIndex === correctIndex,
      })),
    });
  });
}

for (const user of db.users) {
  if (user.role === "STUDENT") {
    user.groupId = groups[0].id;
  } else if (!user.groupId) {
    user.groupId = null;
  }
}

